export const EXPERIENCE_TIME_ZONE = "Asia/Tokyo" as const;

export type ExperienceTimeZone = typeof EXPERIENCE_TIME_ZONE;
export type LocalDate = string;
export type LocalTime = string;
export type UtcInstant = string;
export type OccurrenceId = string;

export type Weekday =
  | "MONDAY"
  | "TUESDAY"
  | "WEDNESDAY"
  | "THURSDAY"
  | "FRIDAY"
  | "SATURDAY"
  | "SUNDAY";

export type Recurrence =
  | { readonly kind: "DAILY" }
  | { readonly kind: "WEEKLY" }
  | { readonly kind: "WEEKENDS" }
  | {
      readonly kind: "SELECTED_WEEKDAYS";
      readonly weekdays: readonly Weekday[];
    };

export interface ScheduleRule {
  readonly id: string;
  readonly timeZone: ExperienceTimeZone;
  readonly startsOn: LocalDate;
  readonly endsOn?: LocalDate;
  readonly localStartTime: LocalTime;
  readonly durationMinutes: number;
  readonly capacity: number;
  readonly bookingCutoffMinutes: number;
  readonly busyBufferBeforeMinutes: number;
  readonly busyBufferAfterMinutes: number;
  readonly recurrence: Recurrence;
}

export type OccurrenceOverride =
  | {
      readonly occurrenceId: OccurrenceId;
      readonly kind: "CLOSE";
    }
  | {
      readonly occurrenceId: OccurrenceId;
      readonly kind: "RESCHEDULE";
      readonly localDate: LocalDate;
      readonly localStartTime: LocalTime;
      readonly durationMinutes?: number;
    };

/** Selling is independent from a moved occurrence. OPEN is stored too so reopening never resets version history. */
export interface OccurrenceSalesState {
  readonly occurrenceId: OccurrenceId;
  readonly desiredState: "OPEN" | "CLOSED";
}

export interface Occurrence {
  readonly id: OccurrenceId;
  readonly ruleId: string;
  /** The date generated by the rule. It does not change when this occurrence moves. */
  readonly sourceLocalDate: LocalDate;
  readonly localDate: LocalDate;
  readonly localStartTime: LocalTime;
  readonly timeZone: ExperienceTimeZone;
  readonly startUtc: UtcInstant;
  readonly endUtc: UtcInstant;
  readonly durationMinutes: number;
  readonly capacity: number;
  readonly bookingCutoffMinutes: number;
  readonly busyBufferBeforeMinutes: number;
  readonly busyBufferAfterMinutes: number;
  readonly status: "OPEN" | "CLOSED";
  readonly rescheduled: boolean;
}

/** Only interval boundaries are accepted; private Google event content has no domain field. */
export interface BusyInterval {
  readonly startUtc: UtcInstant;
  readonly endUtc: UtcInstant;
}

export interface ExpandOccurrencesInput {
  readonly rule: ScheduleRule;
  readonly overrides?: readonly OccurrenceOverride[];
  readonly salesStates?: readonly OccurrenceSalesState[];
  /** Inclusive local date in Asia/Tokyo. */
  readonly fromDate: LocalDate;
  /** Inclusive local date in Asia/Tokyo. */
  readonly toDate: LocalDate;
}

export interface BookingOccurrenceSnapshot {
  readonly occurrenceId: OccurrenceId;
  readonly ruleId: string;
  readonly sourceLocalDate: LocalDate;
  readonly localDate: LocalDate;
  readonly localStartTime: LocalTime;
  readonly timeZone: ExperienceTimeZone;
  readonly startUtc: UtcInstant;
  readonly endUtc: UtcInstant;
  readonly capacityAtAcceptance: number;
  readonly seats: number;
  readonly acceptedAtUtc: UtcInstant;
}

export type GoogleSyncStatus = "FRESH" | "STALE" | "FAILED";

export interface AvailabilityInput {
  readonly occurrence: Occurrence;
  readonly requestedSeats: number;
  readonly confirmedSeats: number;
  readonly heldSeats: number;
  readonly nowUtc: UtcInstant;
  readonly googleCalendar: {
    readonly blockingEnabled: boolean;
    readonly syncStatus: GoogleSyncStatus;
    readonly busyIntervals: readonly BusyInterval[];
  };
  /** Defaults to the legacy seat model when no inventory setting exists. */
  readonly sharedInventory?: {
    readonly bookingMode: "SEAT" | "PRIVATE_GROUP";
    readonly activeGroupCount: number;
    readonly hasInactiveResource: boolean;
    readonly hasResourceConflict: boolean;
    readonly hasResourceGoogleUnavailable?: boolean;
    readonly hasResourceGoogleBusy?: boolean;
  };
}

export type AvailabilityReason =
  | "AVAILABLE"
  | "MANUALLY_CLOSED"
  | "BOOKING_CUTOFF_REACHED"
  | "INSUFFICIENT_CAPACITY"
  | "GROUP_RESERVED"
  | "RESOURCE_INACTIVE"
  | "RESOURCE_BUSY"
  | "RESOURCE_GOOGLE_UNAVAILABLE"
  | "RESOURCE_GOOGLE_BUSY"
  | "GOOGLE_SYNC_UNAVAILABLE"
  | "GOOGLE_BUSY"
  | "EXTERNAL_RESERVATION_UNRESOLVED";

export interface AvailabilityResult {
  readonly bookable: boolean;
  readonly reason: AvailabilityReason;
  /** Seats a new booking may take after all blockers are considered. */
  readonly availableSeats: number;
  /** Capacity left after confirmed bookings and active holds, independent of other blockers. */
  readonly remainingCapacity: number;
  readonly confirmedSeats: number;
  readonly heldSeats: number;
}
